#!/usr/bin/env ruby
# consolidate.rb — HARNESS §4.2 "verdad en disco, no lo dicho".
# Reads research/astNN-items.yaml (source of truth), normalizes verdicts, recomputes
# the utility gate, and emits research/utility-report.md with counts + top items.
# Uses ruby-native YAML (orchestrator python3 has no PyYAML).
require 'yaml'

root = File.expand_path('..', __dir__)
res  = File.join(root, 'research')

def scores_map(item)
  s = item['utility_scores'] || {}
  s = s.transform_keys(&:to_s)
end
def g(s, k)
  v = s[k]
  v.nil? ? nil : v.to_f
end
def gate(a, b, c, d, e)
  if [a, b, c, d, e].any?(&:nil?)
    return ['DISCARD', 0.0]
  end
  avg = (a + d + e) / 3.0
  v = if d <= 2 then 'REFERENCE'
      elsif b >= 4 && avg >= 3.5 && c >= 3 then 'INCLUDE'
      else 'DISCARD'
      end
  [v, avg]
end

files = Dir.glob(File.join(res, 'ast*-items.yaml')).sort
rows = []            # full table
counts = {}          # section => {n,inc,ref,dis,mismatch}
mismatches = []
top = []

files.each do |f|
  sec = File.basename(f, '.yaml')
  data = YAML.load_file(f)
  items = data['items'] || []
  c = { n: 0, inc: 0, ref: 0, dis: 0, mismatch: 0 }
  items.each do |it|
    id = it['id'].to_s
    declared = it['verdict'].to_s.strip.upcase
    declared = 'DISCARD' if declared.empty?
    s = scores_map(it)
    a, b, cc, d, e = g(s, 'A'), g(s, 'B'), g(s, 'C'), g(s, 'D'), g(s, 'E')
    computed, avg = gate(a, b, cc, d, e)
    mismatch = declared != computed
    mismatches << { id: id, sec: sec, declared: declared, computed: computed,
                    scores: [a, b, cc, d, e], avg: avg } if mismatch
    c[:n] += 1
    case computed
    when 'INCLUDE' then c[:inc] += 1
    when 'REFERENCE' then c[:ref] += 1
    else c[:dis] += 1
    end
    impact = it['impact'].to_s
    sev = it['severity_hint'].to_s
    title = it['title'].to_s
    rows << { sec: sec, id: id, verdict: computed, a: a, b: b, c: cc, d: d, e: e,
              avg: avg, sev: sev, impact: impact, title: title, mismatch: mismatch,
              declared: declared }
    top << { id: id, impact: impact, sev: sev, avg: avg, e: (e || 0), title: title,
             verdict: computed } if computed == 'INCLUDE' && avg >= 4.0
  end
  counts[sec] = c
end

def fmt(x); x.nil? ? '-' : format('%.2f', x); end
def scr(x); x.nil? ? '-' : x.to_i.to_s; end

L = []
L << "# Utility Report — Agentic Skills Offensive Checklist (Phase 1)"
L << ''
L << "> Generated by `scripts/consolidate.rb` from on-disk YAML (HARNESS §4.2: disk is truth)."
L << "> Date: 2026-10-14 · Gate: **INCLUDE** if B≥4 AND avg(A,D,E)≥3.5 AND C≥3 · **REFERENCE** if D≤2 · **DISCARD** otherwise."
L << ''
# totals
tn = counts.values.sum { |h| h[:n] }
ti = counts.values.sum { |h| h[:inc] }
tr = counts.values.sum { |h| h[:ref] }
td = counts.values.sum { |h| h[:dis] }
tm = mismatches.size
L << "## Totals"
L << ''
L << "| metric | value |"
L << "|---|---|"
L << "| candidate items | **#{tn}** |"
L << "| INCLUDE | #{ti} |"
L << "| REFERENCE (link, not duplicate) | #{tr} |"
L << "| DISCARD | #{td} |"
L << "| items landing on gate (≈ a section's final checklist size) | ~#{ti} |"
L << "| gate/verdict mismatches (declared vs recomputed) | #{tm} |"
L << ''
L << "## Per-section counts"
L << ''
L << "| section | n | INCLUDE | REFERENCE | DISCARD | mismatch |"
L << "|---|---|---|---|---|---|"
counts.keys.sort.each do |sec|
  h = counts[sec]
  L << "| #{sec} | #{h[:n]} | #{h[:inc]} | #{h[:ref]} | #{h[:dis]} | #{h[:mismatch]} |"
end
L << "| **TOTAL** | **#{tn}** | **#{ti}** | **#{tr}** | **#{td}** | **#{tm}** |"
L << ''
L << "## All items"
L << ''
L << "| id | section | verdict | A | B | C | D | E | avg(ADE) | severity | impact | title | flag |"
L << "|---|---|---|---|---|---|---|---|---|---|---|---|---|"
rows.each do |r|
  flag = r[:mismatch] ? "⚠ declared=#{r[:declared]}" : ''
  t = r[:title].gsub('|', '\\\\|')
  L << "| #{r[:id]} | #{r[:sec].sub('ast', 'AS').sub(/-.*/, '')} | #{r[:verdict]} | #{scr(r[:a])} | #{scr(r[:b])} | #{scr(r[:c])} | #{scr(r[:d])} | #{scr(r[:e])} | #{fmt(r[:avg])} | #{r[:sev]} | #{r[:impact]} | #{t} | #{flag} |"
end
L << ''
L << "## Top INCLUDE items (avg(A,D,E) ≥ 4.0, by impact weight)"
L << ''
L << "| id | impact | severity | avg | E | title |"
L << "|---|---|---|---|---|---|"
weight = { 'RCE' => 5, 'exfil-creds' => 5, 'takeover' => 4, 'persistencia' => 3, 'evasion' => 2 }
top_sorted = top.sort_by { |t| [-(weight[t[:impact]] || 1), -t[:avg], -t[:e], t[:id]] }.first(15)
top_sorted.each do |t|
  L << "| #{t[:id]} | #{t[:impact]} | #{t[:sev]} | #{fmt(t[:avg])} | #{scr(t[:e])} | #{t[:title].gsub('|', '\\\\|')} |"
end
L << ''
if tm > 0
  L << "## Gate/verdict mismatches (review: declared vs recomputed)"
  L << ''
  L << "| id | section | declared | recomputed | A | B | C | D | E |"
  L << "|---|---|---|---|---|---|---|---|---|"
  mismatches.each do |m|
    L << "| #{m[:id]} | #{m[:sec]} | #{m[:declared]} | #{m[:computed]} | #{m[:scores].map { |x| scr(x) }.join(' | ')} |"
  end
  L << ''
  L << "> Declared verdicts reflect agent judgment (e.g., nuanced dedup); recomputed is the raw gate. Divergences are items to spot-check, not errors."
end

out = File.join(res, 'utility-report.md')
File.write(out, L.join("\n") + "\n")
puts "wrote #{out}"
puts "items=#{tn} include=#{ti} reference=#{tr} discard=#{td} mismatch=#{tm}"
